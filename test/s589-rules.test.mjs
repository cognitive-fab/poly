function poly(args, cwd) {
  const env = { ...process.env };
  delete env.NODE_TEST_CONTEXT;
  const r = spawnSync(process.execPath, [CLI, ...args], { cwd, env, timeout: 60_000 });
  return { status: r.status, stdout: r.stdout, out: r.stdout.toString('utf8'), err: r.stderr.toString('utf8') };
}

/** The registry's rules command, after asserting it exists, so that its absence fails on an assertion. */
function rulesCommand() {
  const cmd = commandNamed('rules');
  assert.ok(cmd, 'the registry has a command named rules (PT14, S589)');
  return cmd;
}

/** The page of PT14's layout, built here from the entries as the paragraph states it. */
function page(rules) {
  const blocks = ['# Rules', GENERATED];
  if (rules.length === 0) blocks.push('No rules.');
  let file = null;
  for (const r of rules) {
    if (r.file !== file) { blocks.push(`## ${r.file}`); file = r.file; }
    let clause = `${r.kind}, line ${r.line}`;
    if (r.mitigates) clause += `, mitigates ${r.mitigates.join(', ')}`;
    if (r.implements) clause += `, implements ${r.implements.join(', ')}`;
    if (r.owner.kind === 'policy') clause += r.signature ? `, signed by ${r.signature.by} (sequence ${r.signature.sequence})` : ', not signed';
    blocks.push(`### ${r.id}`, clause, '```poly\n' + r.text + '\n```');
  }
  return blocks.join('\n\n') + '\n';
}

/** Every file under a folder with its bytes, so a run that writes, removes or changes anything shows. */
function snapshot(dir) {
  const out = {};
  const walk = (d) => {
    for (const e of readdirSync(d).sort()) {
      const p = join(d, e);
      if (statSync(p).isDirectory()) walk(p); else out[p] = readFileSync(p).toString('base64');
    }
  };
  walk(dir);
  return out;
}

