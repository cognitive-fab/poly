// M10 step 0 (PT28.1, PT28.4, PT10h, Q9): generated host types, the host check, and edit-and-check.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CERTIFIED_ARTEFACTS } from '@poly/core';
import { commandNamed, COMMANDS } from '@poly/check';
import { ROOT } from './helpers.mjs';

const ROUTER = join(ROOT, 'conformance', 'm4', 'router.poly');
// Under the repository, so the host code resolves @poly/runtime from its node_modules as a host project would.
const WORK = join(ROOT, '.poly', 'test-host-types');

function fresh(name) {
  const dir = join(WORK, name);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  return dir;
}

async function checked(dir, extra = {}) {
  const src = join(dir, 'router.poly');
  copyFileSync(ROUTER, src);
  return commandNamed('check').run({ target: src, root: dir, ...extra });
}

test('PT28.1a: types.d.ts declares the state, the actions, the effects and the completions, with branded Content and Principal', async () => {
  const dir = fresh('decl');
  const r = await checked(dir);
  assert.equal(r.result.verdict, 'CLEAN');
  const text = readFileSync(join(dir, '.poly', 'build', 'support.Ticket', 'types.d.ts'), 'utf8');
  const contract = JSON.parse(readFileSync(join(dir, '.poly', 'build', 'support.Ticket', 'contract.json'), 'utf8'));
  assert.ok(text.startsWith(`// Generated by poly-lower from support.Ticket, module digest ${contract.machineVersion} (PT28.1).`));
  assert.match(text, /export type Content = string & \{ readonly __poly: "Content" \};/);
  assert.match(text, /export type Principal = string & \{ readonly __poly: "Principal" \};/);
  assert.match(text, /"order": 1 \| 2;/);
  assert.match(text, /\| \{ action: "Routed"; data: \{ "branch": "Refund" \| "Reschedule" \| "Status" \| "Complaint" \| "Other"; "conf": number; "margin": number \} \}/);
  assert.match(text, /"decision\.route": \{ "ok": Extract<Action, \{ action: "Routed" \}>\["data"\]; "failed": Extract<Action, \{ action: "RouteFailed" \}>\["data"\] \};/);
});

test('PT28.1c: types.d.ts is a certified artefact', () => {
  assert.ok(CERTIFIED_ARTEFACTS.includes('types.d.ts'));
});

function hostProject(dir, body) {
  writeFileSync(join(dir, 'host.ts'), [
    `import type { PolyRuntime } from '@poly/runtime';`,
    `import type { Action, State } from './.poly/build/support.Ticket/types.js';`,
    `export async function route(rt: PolyRuntime, id: string): Promise<State | null> {`,
    body,
    `  return null;`,
    `}`,
    ``,
  ].join('\n'));
  writeFileSync(join(dir, 'tsconfig.json'), JSON.stringify({ compilerOptions: { strict: true, module: 'nodenext', moduleResolution: 'nodenext', target: 'es2022', skipLibCheck: true, noEmit: true }, files: ['host.ts'] }, null, 2));
  return join(dir, 'tsconfig.json');
}

test('PT28.1b, PT28.1d: host code that dispatches a typed action compiles; a wrong action or wrong data is PL6836 at its line', async () => {
  const good = fresh('host-good');
  await checked(good);
  const ok = await checked(good, { host: hostProject(good, `  await rt.dispatch<Action>(id, 'Received', { text: 'where is my refund' });`) });
  assert.equal(ok.result.host.status, 'ran');
  assert.deepEqual(ok.result.host.diagnostics, []);
  assert.equal(ok.result.verdict, 'CLEAN');

  const bad = fresh('host-bad');
  await checked(bad);
  const r = await checked(bad, { host: hostProject(bad, `  await rt.dispatch<Action>(id, 'Received', { text: 7 });\n  await rt.dispatch<Action>(id, 'Refund', {});`) });
  assert.equal(r.result.host.status, 'ran');
  const codes = r.result.host.diagnostics.map((d) => [d.code, d.at.line]);
  assert.deepEqual(codes, [['PL6836', 4], ['PL6836', 5]]);
  assert.equal(r.result.verdict, 'FINDINGS');
  assert.equal(r.exit, 1);
});

test('PT28.1d, S312: a host check that cannot run is listed as not run, and the verdict is INCONCLUSIVE', async () => {
  const dir = fresh('host-missing');
  const r = await checked(dir, { host: join(dir, 'no-such-tsconfig.json') });
  assert.equal(r.result.host.status, 'not-run');
  assert.equal(r.result.verdict, 'INCONCLUSIVE');
});

test('PT28.4: edit-check is served over MCP and the language server; no command it shares a path with admits or signs', () => {
  const c = commandNamed('edit-check');
  assert.equal(c.mcp, 'poly_edit_check');
  assert.equal(c.lsp, true);
  assert.ok(COMMANDS.some((x) => x.name === 'edit-check'));
});

test('PT28.4a, PT28.4b: an edit is checked in memory; the reply holds the verdict, the findings with their witnesses, and the report path', async () => {
  const dir = fresh('edit');
  const src = join(dir, 'router.poly');
  copyFileSync(ROUTER, src);
  const before = readFileSync(src, 'utf8');
  // A refund on a weaker margin breaks the step property refund-needs-margin.
  const r = await commandNamed('edit-check').run({ module: src, old: 'margin >= 0.3 { status', new: 'margin >= 0.2 { status' });
  assert.equal(r.result.status, 'checked');
  assert.equal(r.result.verdict, 'FINDINGS');
  const f = r.result.findings.find((x) => x.code === 'PL3002');
  assert.ok(f, JSON.stringify(r.result.findings));
  assert.ok(f.witness && f.witness.actions.includes('Routed'));
  assert.ok(existsSync(r.result.report));
  assert.equal(r.result.written, false);
  assert.equal(readFileSync(src, 'utf8'), before, 'not written without apply');
});

test('PT28.4c: with apply, a REFUSED edit is not written; one that checks is written after the check', async () => {
  const dir = fresh('apply');
  const src = join(dir, 'router.poly');
  copyFileSync(ROUTER, src);
  const before = readFileSync(src, 'utf8');
  const refused = await commandNamed('edit-check').run({ module: src, old: 'status\' = Routing', new: 'status\' = Nowhere', apply: true });
  assert.equal(refused.result.verdict, 'REFUSED');
  assert.equal(refused.result.written, false);
  assert.equal(readFileSync(src, 'utf8'), before);
  const ok = await commandNamed('edit-check').run({ module: src, old: 'path property one-routing: count("decision.route") <= 1', new: 'path property one-routing: count("decision.route") <= 2', apply: true });
  assert.equal(ok.result.verdict, 'CLEAN');
  assert.equal(ok.result.written, true);
  assert.ok(readFileSync(src, 'utf8').includes('count("decision.route") <= 2'));
});

test('PT28.4a: an edit whose old text does not occur exactly once is refused before any check, and nothing is written', async () => {
  const dir = fresh('ambiguous');
  const src = join(dir, 'router.poly');
  copyFileSync(ROUTER, src);
  const twice = await commandNamed('edit-check').run({ module: src, old: 'require status', new: 'require !status', apply: true });
  assert.equal(twice.result.status, 'refused');
  assert.match(twice.result.reason, /more than once/);
  const none = await commandNamed('edit-check').run({ module: src, old: 'no such text', new: 'x', apply: true });
  assert.equal(none.result.status, 'refused');
  assert.equal(readFileSync(src, 'utf8'), readFileSync(ROUTER, 'utf8'));
  assert.ok(!existsSync(join(dir, '.poly', 'edit-check', 'build')));
});
