// v1.3.1 documentation: writes adapters/claude-code/skills/poly/findings.md from the diagnostics table (CODES in
// packages/poly-core/src/diagnostics.ts: code, name, stage, severity) and the notes beside this script
// (scripts/skill-findings-notes.json: the meaning and the usual fix of each code). The skill holds no code (S167), so the
// generator lives here and test/skill-findings.test.mjs fails when the file and the table disagree.
//
//   node scripts/make-skill-findings.mjs          write the file
//   node scripts/make-skill-findings.mjs --check  exit 1 when the file is not what the table and the notes give
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CODES } from '@poly/core';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const NOTES_FILE = join(ROOT, 'scripts', 'skill-findings-notes.json');
export const OUT_FILE = join(ROOT, 'adapters', 'claude-code', 'skills', 'poly', 'findings.md');

/** What a severity does to the verdict (PT12.3). */
const VERDICT = { error: 'REFUSED', finding: 'FINDINGS', inconclusive: 'INCONCLUSIVE', warning: 'CLEAN' };

/**
 * Two codes poly-runtime raises as errors without entering CODES (a refusal at load and a refused capability call; grep
 * PL6411 and PL6412 in packages/poly-runtime/src). They are listed apart, so the table stays exactly CODES. The test
 * fails if either enters CODES, so no code is listed twice.
 */
export const OUTSIDE_TABLE = {
  PL6411: {
    name: 'RETRY_UNSAFE_MANIFEST',
    where: 'refused at load (PT33.5)',
    meaning: 'Addressed to the runtime: the build holds an irreversible effect that may be attempted twice with no idempotency in its manifest entry.',
    fix: 'Do not edit around it. PL4003 names the same defect at its source in the program: fix that, then rebuild. Admitting again needs the owner\'s key.',
  },
  PL6412: {
    name: 'NONE_CLASS_WRITE',
    where: 'refused call (PS23.10)',
    meaning: 'Addressed to the runtime: the handler of an effect of class none made a write (not GET or HEAD). The call was refused before the transport and audited.',
    fix: 'If the effect writes, declare its true class (`reversible`, `compensable` or `irreversible`) and give it the retry safety that class needs. Do not send a write from a class none handler.',
  },
};

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

/** The codes the table has and the notes lack, and the notes the table lacks. */
export function disagreement(codes = CODES, notes = JSON.parse(readFileSync(NOTES_FILE, 'utf8'))) {
  const have = Object.keys(codes);
  const noted = Object.keys(notes);
  return { missingNotes: have.filter((c) => !(c in notes)).sort(), unknownNotes: noted.filter((c) => !(c in codes)).sort() };
}

/** The text of findings.md. Deterministic: sorted by code, LF line ends. */
export function render(codes = CODES, notes = JSON.parse(readFileSync(NOTES_FILE, 'utf8'))) {
  const d = disagreement(codes, notes);
  if (d.missingNotes.length || d.unknownNotes.length) throw new Error(`notes and table disagree: missing ${d.missingNotes.join(' ')}; unknown ${d.unknownNotes.join(' ')}`);
  const rows = Object.keys(codes).sort().map((code) => {
    const c = codes[code];
    const n = notes[code];
    return `| \`${code}\` | \`${c.name}\` | ${c.severity}, ${c.stage} | ${cell(n.meaning)} | ${cell(n.fix)} |`;
  });
  const count = Object.keys(codes).length;
  const outside = Object.entries(OUTSIDE_TABLE).sort(([a], [b]) => a.localeCompare(b)).map(([code, o]) => `| \`${code}\` | \`${o.name}\` | ${o.where} | ${cell(o.meaning)} | ${cell(o.fix)} |`);
  return `<!-- Generated by scripts/make-skill-findings.mjs from CODES (packages/poly-core/src/diagnostics.ts) and scripts/skill-findings-notes.json. Do not edit by hand: change the notes and run the script. -->

# poly findings: what each diagnostic means and the usual fix

\`poly_check\` prints each diagnostic as \`PLxxxx NAME\`, a line, a message, and for a finding a witness. This file lists the ${count} codes of the diagnostics table, and two more that the runtime raises outside it. Find the code, read the meaning, apply the fix, and check again.

## How to read a row

- **Severity** decides the verdict. \`error\` gives ${VERDICT.error}: the program is not admitted until it is fixed. \`finding\` gives ${VERDICT.finding}: a defect in the program, with a witness you can export with \`poly_witness\`. \`inconclusive\` gives ${VERDICT.inconclusive}: a bound was hit, and the check did not prove the property. Nothing but \`CLEAN\` is done.
- **Stage** is where the check found it: parse, types, lower, validate, translation-validation, model-check, effects, composition, configuration, deadlock, liveness, lint, policy, runtime, replay or host.
- **Fix** is the usual repair, not the only one. A fix marked \`poly_fix offers this\` is a typed edit: apply it with \`poly_fix\` after a fresh check, or the fix is refused as stale (\`PL0201\`).
- **Toolchain and runtime codes** (\`PL2001\`, \`PL2501\`, \`PL2401\`, the load and replay codes) are not the author's fault. Report them with the code, the file and the witness. Do not edit the program to hide them.
- **A person's key.** Accepting a finding, approving an escalation and signing a policy or a keyring need a person's key. The agent does not do these, and the tools do not offer them.
- **Never** weaken a property, a check domain or a bound so that a code goes away. Fix the program, or report the finding.

## Codes

| Code | Name | Severity, stage | Meaning | Usual fix |
|---|---|---|---|---|
${rows.join('\n')}

## Raised outside the table

| Code | Name | Where | Meaning | Usual fix |
|---|---|---|---|---|
${outside.join('\n')}

## Glossary

- **Bound hit:** the check reached a limit of its search before it proved the property, so the verdict is \`INCONCLUSIVE\`.
- **Finding:** a defect in the program that the check proves, shown with a witness.
- **Refused:** the program breaks a rule of the language; it is not checked further and not admitted.
- **Stage:** one pass of the check; a later stage does not run when an earlier one refuses the program.
- **Typed fix:** an edit to one node of the syntax tree, applied only if the node is unchanged since the check.
- **Witness:** the steps, listed by the checker, by which a property is broken.
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = render();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT_FILE, 'utf8').replace(/\r\n/g, '\n'); } catch { /* absent */ }
    if (have !== text) { console.error('findings.md is not what the diagnostics table and the notes give; run node scripts/make-skill-findings.mjs'); process.exit(1); }
  } else {
    writeFileSync(OUT_FILE, text);
    console.log(`wrote ${OUT_FILE} (${Object.keys(CODES).length} codes)`);
  }
}
