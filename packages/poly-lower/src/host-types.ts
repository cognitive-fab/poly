// Generated host types (PT28.1, PT10h, S311): types.d.ts beside each machine's artefacts, which host code compiles
// against. poly-ref writes the declarations it expects from its own model and compares them with this file
// (artefacts.ts), so this is one of two independent writers of the same text.
import type * as A from '@poly/core';
import type { Ty, TypeEnv } from '@poly/core';
import { effectKind } from '@poly/core';
import type { Layout } from './layout.js';
import { tyOfTypeExpr, isPayloadUnion } from './layout.js';

/** S311: an integer range of at most this many values is the union of its literals; any other is number. */
const LITERAL_RANGE = 64;

export interface HostTypesInput {
  module: A.Module;
  machine: A.Machine;
  env: TypeEnv;
  layout: Layout;
  version: string;
  program: A.Module[];
  /** The broken lowering types-widen-param (PT10h): the first parameter of the first action that has one as unknown. */
  widen?: boolean;
}

const q = (s: string) => JSON.stringify(s);

export function hostTypes(h: HostTypesInput): string {
  const { env, module } = h;
  const members = (name: string): string[] => {
    const u = env.unions.get(name);
    if (u) return u.ctors.map((c) => c.name);
    // S190: an enum of another module, m.E, read from that module's declaration.
    const i = name.lastIndexOf('.');
    const d = h.program.find((m) => m.name === name.slice(0, i))?.decls.find((x) => (x.kind === 'EnumDecl' || x.kind === 'TypeDecl') && x.name === name.slice(i + 1));
    if (!d) throw new Error(`poly-lower: no enum ${name} for the host types`);
    return d.kind === 'EnumDecl' ? d.members : (d as A.TypeDecl).ctors.map((c) => c.name);
  };
  const lits = (xs: string[]) => xs.map(q).join(' | ');
  const ts = (t: Ty): string => {
    switch (t.k) {
      case 'bool': return 'boolean';
      case 'int': return Number.isFinite(t.lo) && Number.isFinite(t.hi) && t.hi - t.lo + 1 <= LITERAL_RANGE ? Array.from({ length: t.hi - t.lo + 1 }, (_, k) => String(t.lo + k)).join(' | ') : 'number';
      case 'conf': return 'number';
      case 'string': return 'string';
      case 'ref': return 'string | null';
      case 'principal': return 'Principal | null';
      case 'content': return 'Content | null';
      // PS1.4b: the runtime's reference; a host reads its count and passes it on.
      case 'items': return 'Items';
      case 'record': return `{ ${env.records.get(t.name)!.fields.map((f) => `${q(f.name)}: ${ts(tyOfTypeExpr(f.type, env))}`).join('; ')} }`;
      case 'map': return t.array ? `(${ts(t.value)})[]` : `{ ${members((t.key as { name: string }).name).map((c) => `${q(c)}: ${ts(t.value)}`).join('; ')} }`;
      case 'union': {
        if (!isPayloadUnion(env, t)) return lits(members(t.name));
        // S65: below the top of a field, a union with payloads is one object per constructor.
        return env.unions.get(t.name)!.ctors.map((c) => `{ "$": ${q(c.name)}${c.fields.map((f) => `; ${q(f.name)}: ${ts(tyOfTypeExpr(f.type, env))}`).join('')} }`).join(' | ');
      }
      default: return 'unknown';
    }
  };
  const lines: string[] = [];
  lines.push(`// Generated by poly-lower from ${module.name}.${h.machine.name}, module digest ${h.version} (PT28.1). Do not edit: change the poly source and rebuild.`);
  lines.push(`export type Content = string & { readonly __poly: "Content" };`);
  lines.push(`export type Principal = string & { readonly __poly: "Principal" };`);
  lines.push(`export type Items = { readonly count: number; readonly __poly: "Items" };`);
  // PS9.1b: the state as the host reads it, the flat keys in the contract's order.
  lines.push(`export interface State {`);
  for (const l of h.layout.fields) {
    if (l.kind === 'union') {
      const u = env.unions.get((l.ty as { name: string }).name)!;
      lines.push(`  ${q(l.field)}: ${lits(u.ctors.map((c) => c.name))};`);
      for (const [p, key] of l.payloads!) {
        const pt = u.ctors.flatMap((c) => c.fields).find((f) => f.name === p)!;
        lines.push(`  ${q(key)}: ${ts(tyOfTypeExpr(pt.type, env))} | null;`);
      }
      continue;
    }
    lines.push(`  ${q(l.field)}: ${ts(l.ty)};`);
  }
  lines.push(`}`);
  const actions = h.machine.items.filter((i): i is A.Action => i.kind === 'Action');
  let widened = !h.widen;
  const dataOf = (a: A.Action) => `{ ${a.params.map((p) => {
    let t = ts(tyOfTypeExpr(p.type, env));
    if (!widened) { t = 'unknown'; widened = true; }
    return `${q(p.name)}: ${t}`;
  }).join('; ')} }`.replace('{  }', '{}');
  lines.push(`export type Action =`);
  if (!actions.length) lines.push(`  never;`);
  actions.forEach((a, i) => lines.push(`  | { action: ${q(a.name)}; data: ${dataOf(a)} }${i === actions.length - 1 ? ';' : ''}`));
  // PT6.1, PD1.7: each effect's kind, and each decision's decision.<d>, with its payload.
  const effects = h.machine.items.filter((i): i is A.EffectDecl => i.kind === 'EffectDecl');
  const decisions = h.machine.items.filter((i): i is A.Decision => i.kind === 'Decision');
  // S41, PS17.2: the kind the manifest gives the effect.
  const kindOf = (e: A.EffectDecl) => effectKind(e);
  const entries: [string, A.Param[], A.EffOutcomeItem[]][] = [
    ...effects.map((e): [string, A.Param[], A.EffOutcomeItem[]] => [kindOf(e), e.params, e.items.filter((x): x is A.EffOutcomeItem => x.kind === 'EffOutcome')]),
    ...decisions.map((d): [string, A.Param[], A.EffOutcomeItem[]] => [`decision.${d.name}`, d.params, d.items.filter((x): x is A.EffOutcomeItem => x.kind === 'EffOutcome')]),
  ];
  const payload = (ps: A.Param[]) => `{ ${ps.map((p) => `${q(p.name)}: ${ts(tyOfTypeExpr(p.type, env))}`).join('; ')} }`.replace('{  }', '{}');
  lines.push(`export interface Effects {`);
  for (const [kind, ps] of entries) lines.push(`  ${q(kind)}: ${payload(ps)};`);
  lines.push(`}`);
  lines.push(`export interface Completions {`);
  for (const [kind, , outs] of entries) {
    const order = ['ok', 'failed', 'exhausted'];
    const known = outs.filter((o) => order.includes(o.outcome)).sort((x, y) => order.indexOf(x.outcome) - order.indexOf(y.outcome));
    lines.push(`  ${q(kind)}: { ${known.map((o) => `${q(o.outcome)}: Extract<Action, { action: ${q(o.action)} }>["data"]`).join('; ')} };`.replace('{  }', '{}'));
  }
  lines.push(`}`);
  return lines.join('\n') + '\n';
}
